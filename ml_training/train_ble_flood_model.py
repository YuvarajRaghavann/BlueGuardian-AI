#!/usr/bin/env python3
"""Train and evaluate a session-held-out BLE flood classifier and export compact trees."""
from __future__ import annotations

import argparse
import json
import math
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
)
from sklearn.model_selection import GroupShuffleSplit

FEATURE_COLUMNS = [
    "observation_count",
    "observations_per_second",
    "unique_addresses",
    "unique_address_fraction",
    "max_address_fraction",
    "rssi_mean",
    "rssi_std",
    "rssi_observation_fraction",
]
LABELS = ["benign", "ble_flood"]
POSITIVE_LABEL = "ble_flood"
IMPUTE_FALLBACKS = {
    "observation_count": 0.0,
    "observations_per_second": 0.0,
    "unique_addresses": 0.0,
    "unique_address_fraction": 0.0,
    "max_address_fraction": 0.0,
    "rssi_mean": -100.0,
    "rssi_std": 0.0,
    "rssi_observation_fraction": 0.0,
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True, type=Path, help="CSV generated by extract_pcap_windows.py")
    parser.add_argument("--model-output", required=True, type=Path, help="Output JSON tree ensemble")
    parser.add_argument("--report-output", required=True, type=Path, help="Output JSON evaluation report")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--test-size", type=float, default=0.25)
    parser.add_argument("--minimum-windows-per-class", type=int, default=10)
    parser.add_argument("--minimum-sessions-per-class", type=int, default=2)
    parser.add_argument("--decision-threshold", type=float, default=0.5)
    parser.add_argument("--max-acceptable-fpr", type=float, default=0.02)
    parser.add_argument("--min-acceptable-recall", type=float, default=0.90)
    return parser.parse_args()


def find_group_split(
    X: pd.DataFrame,
    y: pd.Series,
    groups: pd.Series,
    test_size: float,
    seed: int,
    attempts: int = 1024,
) -> tuple[np.ndarray, np.ndarray]:
    """Find a group split with both labels in both sets; individual windows never leak."""
    unique_groups = groups.nunique()
    if unique_groups < 4:
        raise ValueError(
            f"Only {unique_groups} independent sessions are available. At least 4 sessions "
            "across both labels are required to keep all labels in both train and test."
        )

    effective_test_size = test_size if unique_groups >= 8 else max(test_size, 0.5)
    splitter = GroupShuffleSplit(
        n_splits=attempts,
        test_size=effective_test_size,
        random_state=seed,
    )
    all_labels = set(LABELS)
    for train_idx, test_idx in splitter.split(X, y, groups):
        if (
            set(y.iloc[train_idx].unique()) == all_labels
            and set(y.iloc[test_idx].unique()) == all_labels
        ):
            return train_idx, test_idx
    raise ValueError(
        "Could not create a session-independent split containing both labels in train and test. "
        "Add more independent benign and BLE-flood captures; do not split adjacent windows "
        "from one capture across train and test."
    )


def imputation_values(train: pd.DataFrame) -> dict[str, float]:
    values: dict[str, float] = {}
    for name in FEATURE_COLUMNS:
        numeric = pd.to_numeric(train[name], errors="coerce").replace([np.inf, -np.inf], np.nan)
        median = numeric.median()
        fallback = IMPUTE_FALLBACKS[name]
        values[name] = float(median) if pd.notna(median) and math.isfinite(float(median)) else fallback
    return values


def impute(frame: pd.DataFrame, fill: dict[str, float]) -> pd.DataFrame:
    result = frame[FEATURE_COLUMNS].copy()
    for name in FEATURE_COLUMNS:
        result[name] = pd.to_numeric(result[name], errors="coerce")
        result[name] = result[name].replace([np.inf, -np.inf], np.nan).fillna(fill[name])
    return result.astype(float)


def export_tree(estimator: Any, positive_index: int, negative_index: int) -> dict[str, Any]:
    tree = estimator.tree_
    nodes: list[dict[str, Any]] = []
    for index in range(tree.node_count):
        left = int(tree.children_left[index])
        right = int(tree.children_right[index])
        value = np.asarray(tree.value[index][0], dtype=float)
        total = float(value.sum())
        positive_prob = float(value[positive_index] / total) if total > 0 else 0.0
        negative_prob = float(value[negative_index] / total) if total > 0 else 1.0
        if left == right or left < 0 or right < 0:
            nodes.append({
                "feature": -1,
                "threshold": 0.0,
                "left": -1,
                "right": -1,
                "benignProbability": negative_prob,
                "bleFloodProbability": positive_prob,
            })
        else:
            nodes.append({
                "feature": int(tree.feature[index]),
                "threshold": float(tree.threshold[index]),
                "left": left,
                "right": right,
                "benignProbability": negative_prob,
                "bleFloodProbability": positive_prob,
            })
    return {"nodes": nodes}


def main() -> int:
    args = parse_args()
    if not 0.1 <= args.test_size <= 0.5:
        raise SystemExit("--test-size must be between 0.1 and 0.5")
    if not 0.0 < args.decision_threshold < 1.0:
        raise SystemExit("--decision-threshold must be between 0 and 1")
    if not 0.0 <= args.max_acceptable_fpr <= 1.0:
        raise SystemExit("--max-acceptable-fpr must be between 0 and 1")
    if not 0.0 <= args.min_acceptable_recall <= 1.0:
        raise SystemExit("--min-acceptable-recall must be between 0 and 1")
    if not args.data.is_file():
        raise SystemExit(f"Feature CSV not found: {args.data}")

    frame = pd.read_csv(args.data)
    required = {"label", "session_id", *FEATURE_COLUMNS}
    missing = sorted(required - set(frame.columns))
    if missing:
        raise SystemExit(f"Feature CSV is missing required columns: {', '.join(missing)}")

    frame = frame.copy()
    frame["label"] = frame["label"].astype(str).str.strip().str.lower()
    frame["session_id"] = frame["session_id"].astype(str).str.strip()
    frame = frame[frame["label"].isin(LABELS) & frame["session_id"].ne("")].reset_index(drop=True)
    if frame.empty:
        raise SystemExit("No rows remain after validating labels and session IDs.")

    counts = frame["label"].value_counts().to_dict()
    if any(counts.get(label, 0) < args.minimum_windows_per_class for label in LABELS):
        raise SystemExit(
            f"Insufficient windows per class: {counts}. Need at least "
            f"{args.minimum_windows_per_class} for each of {LABELS}."
        )
    sessions_by_class = {
        label: int(frame.loc[frame["label"] == label, "session_id"].nunique())
        for label in LABELS
    }
    if any(value < args.minimum_sessions_per_class for value in sessions_by_class.values()):
        raise SystemExit(
            f"Insufficient independent sessions per class: {sessions_by_class}. Need at least "
            f"{args.minimum_sessions_per_class} for each class; do not treat windows as sessions."
        )
    # A session must not have mixed ground truth labels in this first binary experiment.
    mixed = frame.groupby("session_id")["label"].nunique()
    if (mixed > 1).any():
        raise SystemExit(
            "Some session_id values contain both labels. Use separate capture/session IDs only "
            "when that split reflects genuinely independent collection sessions. For a single "
            "capture containing an attack phase, annotate non-overlapping labeled intervals "
            "and keep the entire capture group in one side of the split."
        )

    groups = frame["session_id"]
    raw_X = frame[FEATURE_COLUMNS]
    y = frame["label"]
    train_idx, test_idx = find_group_split(
        raw_X, y, groups, args.test_size, args.seed
    )

    train_frame = raw_X.iloc[train_idx]
    test_frame = raw_X.iloc[test_idx]
    fill = imputation_values(train_frame)
    X_train = impute(train_frame, fill)
    X_test = impute(test_frame, fill)
    y_train = y.iloc[train_idx]
    y_test = y.iloc[test_idx]

    model = RandomForestClassifier(
        n_estimators=64,
        max_depth=7,
        min_samples_leaf=3,
        class_weight="balanced_subsample",
        random_state=args.seed,
        n_jobs=-1,
    )
    model.fit(X_train, y_train)

    class_index = {str(name): index for index, name in enumerate(model.classes_)}
    positive_index = class_index[POSITIVE_LABEL]
    negative_index = class_index["benign"]
    positive_scores = model.predict_proba(X_test)[:, positive_index]
    predictions = np.where(positive_scores >= args.decision_threshold, POSITIVE_LABEL, "benign")
    matrix = confusion_matrix(y_test, predictions, labels=LABELS)
    true_benign = int(matrix[0].sum())
    false_positives = int(matrix[0, 1])
    fpr = float(false_positives / true_benign) if true_benign else 1.0
    flood_recall = float(recall_score(y_test, predictions, pos_label=POSITIVE_LABEL, zero_division=0))
    metrics = {
        "accuracy": float(accuracy_score(y_test, predictions)),
        "balanced_accuracy": float(balanced_accuracy_score(y_test, predictions)),
        "macro_f1": float(f1_score(y_test, predictions, average="macro", zero_division=0)),
        "benign_precision": float(precision_score(y_test, predictions, pos_label="benign", zero_division=0)),
        "benign_recall": float(recall_score(y_test, predictions, pos_label="benign", zero_division=0)),
        "ble_flood_precision": float(precision_score(y_test, predictions, pos_label=POSITIVE_LABEL, zero_division=0)),
        "ble_flood_recall": flood_recall,
        "ble_flood_f1": float(f1_score(y_test, predictions, pos_label=POSITIVE_LABEL, zero_division=0)),
        "benign_false_positive_rate": fpr,
        "decision_threshold": float(args.decision_threshold),
        "confusion_matrix_labels": LABELS,
        "confusion_matrix": matrix.tolist(),
    }

    preliminary_gates = {
        "session_independent_holdout": True,
        "both_classes_in_train_and_test": True,
        "benign_false_positive_rate_within_limit": fpr <= args.max_acceptable_fpr,
        "ble_flood_recall_within_limit": flood_recall >= args.min_acceptable_recall,
        "thresholds": {
            "max_acceptable_fpr": args.max_acceptable_fpr,
            "min_acceptable_recall": args.min_acceptable_recall,
        },
    }
    promotion_candidate = all([
        preliminary_gates["session_independent_holdout"],
        preliminary_gates["both_classes_in_train_and_test"],
        preliminary_gates["benign_false_positive_rate_within_limit"],
        preliminary_gates["ble_flood_recall_within_limit"],
    ])

    report = {
        "model_name": "BlueGuardian BLE Flood Random Forest",
        "model_version": "0.1.0-candidate",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "status": "candidate_not_production_validated",
        "dataset_csv": str(args.data),
        "sklearn_version": sklearn.__version__,
        "seed": args.seed,
        "feature_names": FEATURE_COLUMNS,
        "rows_by_class": counts,
        "sessions_by_class": sessions_by_class,
        "train_rows": int(len(train_idx)),
        "test_rows": int(len(test_idx)),
        "train_sessions": sorted(groups.iloc[train_idx].unique().tolist()),
        "test_sessions": sorted(groups.iloc[test_idx].unique().tolist()),
        "metrics": metrics,
        "classification_report": classification_report(
            y_test, predictions, labels=LABELS, output_dict=True, zero_division=0
        ),
        "preliminary_gates": preliminary_gates,
        "preliminary_gates_passed": promotion_candidate,
        "deployment_decision": (
            "CANDIDATE_FOR_REVIEW_ONLY; requires Android parity, new-device false-positive tests, "
            "and an independent untouched evaluation before promotion."
        ),
    }

    model_artifact = {
        "status": "candidate",
        "modelName": "BlueGuardian BLE Flood Random Forest",
        "modelVersion": "0.1.0-candidate",
        "labelSemantics": {
            "benign": "Benign BLE advertising window under the dataset's recorded conditions.",
            "ble_flood": "Labeled BLE advertisement-flood/spam window under the dataset's recorded conditions.",
        },
        "featureNames": FEATURE_COLUMNS,
        "imputationValues": fill,
        "decisionThreshold": float(args.decision_threshold),
        "trees": [
            export_tree(tree, positive_index, negative_index)
            for tree in model.estimators_
        ],
        "evaluationSummary": {
            "accuracy": metrics["accuracy"],
            "balancedAccuracy": metrics["balanced_accuracy"],
            "bleFloodPrecision": metrics["ble_flood_precision"],
            "bleFloodRecall": metrics["ble_flood_recall"],
            "bleFloodF1": metrics["ble_flood_f1"],
            "benignFalsePositiveRate": metrics["benign_false_positive_rate"],
            "sessionIndependentHoldout": True,
            "preliminaryGatesPassed": promotion_candidate,
        },
        "deploymentStatus": "disabled_until_explicit_review",
    }

    args.model_output.parent.mkdir(parents=True, exist_ok=True)
    args.report_output.parent.mkdir(parents=True, exist_ok=True)
    args.model_output.write_text(json.dumps(model_artifact, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    args.report_output.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    print(json.dumps({
        "model_output": str(args.model_output),
        "report_output": str(args.report_output),
        "metrics": metrics,
        "preliminary_gates_passed": promotion_candidate,
        "deployment_status": "disabled_until_explicit_review",
        "train_sessions": report["train_sessions"],
        "test_sessions": report["test_sessions"],
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
